// Refreshes gol/oembed-providers.js from the official oEmbed provider list
// (https://oembed.com/providers.json), keeping only what Gol needs:
// URL patterns and the JSON endpoint. Run: node scripts/update-oembed-providers.mjs
import { writeFile } from "node:fs/promises";

const res = await fetch("https://oembed.com/providers.json");
if (!res.ok) throw new Error(`oembed.com answered HTTP ${res.status}`);
const providers = await res.json();
const out = [];
for (const p of providers) {
  for (const e of p.endpoints || []) {
    if (!e.url || !e.schemes?.length || !/^https:/.test(e.url)) continue;
    out.push({ name: p.provider_name, endpoint: e.url.replace("{format}", "json"), schemes: e.schemes });
  }
}
await writeFile(new URL("../gol/oembed-providers.js", import.meta.url),
  "// Generated by scripts/update-oembed-providers.mjs from https://oembed.com/providers.json\nexport default " + JSON.stringify(out) + ";\n");
console.log(`saved ${out.length} oEmbed endpoints from ${providers.length} providers`);
